MAX_NAME_LENGTH = 64
MAX_DESCRIPTION_LENGTH = 1024


def default_skill_name(bundle: SkillBundle) -> str:
    """Skill name: lowercase, hyphenated, at most 64 characters."""
    if bundle.options.name:
        return slugify(bundle.options.name, fallback="skill", max_length=MAX_NAME_LENGTH)
    base = slugify(bundle.graph.domain or bundle.graph.graph_id, fallback="graph", max_length=MAX_NAME_LENGTH - 9)
    return f"{base}-playbook"[:MAX_NAME_LENGTH]


def default_description(bundle: SkillBundle) -> str:
    if bundle.options.description:
        return truncate(bundle.options.description, MAX_DESCRIPTION_LENGTH)
    domain = bundle.domain
    titles = [tree.title for tree in bundle.trees[:6]]
    stats = bundle.stats
    if bundle.options.lang == EN:
        text = (
            f"Decision playbooks for the {domain} domain, compiled from a knowledge graph of "
            f"{stats.node_count} nodes and {stats.relation_count} relations. Use when diagnosing, "
            f"triaging or explaining {domain} problems: it routes a symptom to the matching decision tree, "
            f"lists candidate causes, checks, commands and reference cases with source citations."
        )
        if titles:
            text += " Covered entries: " + "; ".join(truncate(title, 60) for title in titles) + "."
    else:
        text = (
            f"{domain} 领域的决策与排查手册，由包含 {stats.node_count} 个节点、{stats.relation_count} 条关系的知识图谱生成。"
            f"当需要定位、排查或解释 {domain} 相关问题时使用：按现象路由到对应决策树，给出候选原因、检查项、命令示例与案例出处。"
        )
        if titles:
            text += "覆盖入口：" + "；".join(truncate(title, 40) for title in titles) + "。"
    return truncate(text, MAX_DESCRIPTION_LENGTH)


