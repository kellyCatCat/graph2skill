def _routing_table(bundle: SkillBundle, from_dir: str = "") -> List[str]:
    header = (
        f"| {t(bundle, 'col_scenario')} | {t(bundle, 'col_type')} | {t(bundle, 'col_size')} | "
        f"{t(bundle, 'col_depth')} | {t(bundle, 'col_source')} | {t(bundle, 'col_file')} |"
    )
    lines = [header, "| --- | --- | --- | --- | --- | --- |"]
    for tree in bundle.trees:
        node = tree.entry_node
        type_label = node_type_label(node.type, bundle.options.lang) if node else "?"
        sources = ", ".join(node.sources) if node and node.sources else ", ".join(tree.sources)
        lines.append(
            "| {title} | {type} | {size} | {depth} | {sources} | [{path}]({path}) |".format(
                title=escape_table_cell(truncate(tree.title, 70)),
                type=escape_table_cell(type_label),
                size=tree.size,
                depth=tree.max_depth,
                sources=escape_table_cell(sources or "-"),
                path=relative_link(bundle.playbook_path(tree), from_dir),
            )
        )
    return lines


def render_playbook(bundle: SkillBundle, tree: ResolvedTree) -> str:
    node = tree.entry_node
    lines: List[str] = [f"# {t(bundle, 'playbook')}: {one_line(tree.title)}", ""]
    meta = [f"{t(bundle, 'entry_node')}: `{tree.entry_node_id}`", f"treeId: `{tree.tree_id}`"]
    if node and node.sources:
        meta.append(f"{t(bundle, 'sources')}: {_sources_text(node.sources)}")
    meta.append(f"{t(bundle, 'col_size')}: {tree.size}")
    lines += ["> " + " · ".join(meta), ""]
    if node and node.description and one_line(node.description) != one_line(node.label):
        lines += [one_line(node.description), ""]

    diagram = mermaid_lines(bundle, tree)
    if diagram:
        lines += [f"## {t(bundle, 'diagram')}", ""] + diagram

    lines += [f"## {t(bundle, 'decision_path')}", ""]
    lines += decision_path_lines(bundle, tree.root)
    lines += ["", f"## {t(bundle, 'node_details')}", ""]

    rendered: set = set()
    for view in tree.root.iter_views():
        if view.node is None or view.node_id in rendered:
            continue
        rendered.add(view.node_id)
        lines += node_detail_lines(bundle, view.node, level=3, children=view.children)
    return "\n".join(lines).rstrip() + "\n"


def render_overview(bundle: SkillBundle) -> str:
    graph = bundle.graph
    stats = bundle.stats
    lines = [f"# {t(bundle, 'overview')}", "", "| key | value |", "| --- | --- |"]
    rows = [
        ("graphId", graph.graph_id),
        ("domain", graph.domain or "-"),
        ("schemaVersion", graph.schema_version),
        ("nodes", str(stats.node_count)),
        ("relations", str(stats.relation_count)),
        ("decisionTrees", str(stats.tree_count)),
        ("entryNodeIds", str(len(graph.entry_node_ids))),
        ("commands", str(stats.command_count)),
        ("provenance", str(stats.provenance_count)),
    ]
    lines += [f"| {escape_table_cell(key)} | {escape_table_cell(value)} |" for key, value in rows]
    lines += ["", f"## {t(bundle, 'node_types')}", "", f"| {t(bundle, 'col_type')} | count |", "| --- | --- |"]
    for node_type, count in stats.node_types.items():
        lines.append(f"| {escape_table_cell(node_type_label(node_type, bundle.options.lang))} (`{node_type}`) | {count} |")
    lines += ["", f"## {t(bundle, 'relation_types')}", "", f"| {t(bundle, 'col_type')} | count |", "| --- | --- |"]
    for rel_type, count in stats.relation_types.items():
        lines.append(f"| {escape_table_cell(relation_label(rel_type, bundle.options.lang))} (`{rel_type}`) | {count} |")
    lines += ["", f"## {t(bundle, 'routing')}", ""] + _routing_table(bundle, from_dir="references")
    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_catalog(bundle: SkillBundle) -> str:
    lines = [f"# {t(bundle, 'catalog')}", ""]
    by_type: Dict[str, List[Node]] = {}
    for node in bundle.graph.nodes.values():
        by_type.setdefault(node.type, []).append(node)
    for node_type in sorted(by_type, key=lambda key: (-len(by_type[key]), key)):
        nodes = sorted(by_type[node_type], key=lambda item: item.id)
        lines += [
            f"## {node_type_label(node_type, bundle.options.lang)} (`{node_type}`, {len(nodes)})",
            "",
            f"| id | {t(bundle, 'col_scenario')} | {t(bundle, 'in_playbook')} |",
            "| --- | --- | --- |",
        ]
        for node in nodes:
            tree = bundle.tree_for_node(node.id)
            target = (
                f"[{escape_table_cell(truncate(tree.title, 40))}]"
                f"({relative_link(bundle.playbook_path(tree), 'references')}#{anchor(node.id)})"
                if tree
                else "-"
            )
            lines.append(f"| `{escape_table_cell(node.id)}` | {escape_table_cell(truncate(node.label, 80))} | {target} |")
        lines.append("")

    uncovered = bundle.uncovered_node_ids()
    if uncovered:
        lines += [f"## {t(bundle, 'uncovered')} ({len(uncovered)})", ""]
        for node_id in uncovered:
            node = bundle.graph.nodes[node_id]
            lines += node_detail_lines(bundle, node, level=3)
    return "\n".join(lines).rstrip() + "\n"


def render_commands(bundle: SkillBundle) -> str:
    lines = [f"# {t(bundle, 'command_index')}", ""]
    rows: List[str] = []
    for node in sorted(bundle.graph.nodes.values(), key=lambda item: item.id):
        tree = bundle.tree_for_node(node.id)
        for command in node.commands:
            location = (
                f"[{escape_table_cell(truncate(tree.title, 30))}]"
                f"({relative_link(bundle.playbook_path(tree), 'references')}#{anchor(node.id)})"
                if tree
                else f"[node-catalog](node-catalog.md#{anchor(node.id)})"
            )
            rows.append(
                f"| `{escape_table_cell(truncate(command, 120))}` | {escape_table_cell(truncate(node.label, 50))} | {location} |"
            )
    if not rows:
        lines.append("-")
        return "\n".join(lines) + "\n"
    lines += [f"| command | {t(bundle, 'col_scenario')} | {t(bundle, 'in_playbook')} |", "| --- | --- | --- |"]
    lines += rows
    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_sources(bundle: SkillBundle) -> str:
    lines = [f"# {t(bundle, 'source_index')}", ""]
    by_path: Dict[str, List[tuple]] = {}
    for node in bundle.graph.nodes.values():
        for prov in node.provenance:
            by_path.setdefault(prov.source_path or "(unknown)", []).append((node, prov))
    for relation in bundle.graph.relations.values():
        for prov in relation.provenance:
            by_path.setdefault(prov.source_path or "(unknown)", []).append((relation, prov))
    if not by_path:
        lines.append("-")
        return "\n".join(lines) + "\n"
    for source_path in sorted(by_path):
        entries = by_path[source_path]
        lines += [f"## `{source_path}`", "", t(bundle, "references_count", count=len(entries)), ""]
        seen: set = set()
        for owner, prov in entries:
            key = (prov.locator, prov.excerpt[:60])
            if key in seen:
                continue
            seen.add(key)
            owner_label = getattr(owner, "label", None) or getattr(owner, "id", "")
            head = prov.locator or owner_label
            lines.append(f"- **{escape_table_cell(truncate(head, 100))}** — `{getattr(owner, 'id', '')}`")
            if prov.excerpt:
                lines.append(f"  > {truncate(prov.excerpt, bundle.options.excerpt_limit)}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_report(bundle: SkillBundle) -> str:
    lines = [f"# {t(bundle, 'report')}", "", f"## {t(bundle, 'stats')}", ""]
    stats = bundle.stats
    lines += [
        f"- {t(bundle, 'r_nodes')}: {stats.node_count}",
        f"- {t(bundle, 'r_relations')}: {stats.relation_count}",
        f"- {t(bundle, 'r_trees')}: {stats.tree_count}",
        f"- {t(bundle, 'r_commands')}: {stats.command_count}",
        f"- {t(bundle, 'r_provenance')}: {stats.provenance_count}",
        f"- {t(bundle, 'r_orphans')}: {stats.orphan_count}",
        "",
    ]
    report = bundle.merge_report
    if report is not None:
        lines += [f"## {t(bundle, 'merge')}", ""]
        kept = t(bundle, "r_kept")
        lines += [
            f"- {t(bundle, 'r_inputs')}: {len(report.origins)}",
            f"- {t(bundle, 'r_graph_ids')}: {', '.join(f'`{gid}`' for gid in report.graph_ids) or '-'}",
            f"- {t(bundle, 'r_nodes_read')}: {report.node_total_in} → {kept} {stats.node_count}",
            f"- {t(bundle, 'r_relations_read')}: {report.relation_total_in} → {kept} {stats.relation_count}",
            f"- {t(bundle, 'r_merged_nodes')}: {len(report.merged_node_ids)}",
            f"- {t(bundle, 'r_merged_relations')}: {len(report.merged_relation_keys)}",
            "",
        ]
        for origin in report.origins:
            lines.append(f"- {t(bundle, 'r_source_file')}: `{origin}`")
        lines.append("")
        if report.conflicts:
            lines += [f"### {t(bundle, 'r_conflicts')}", ""]
            lines += [
                "- "
                + t(
                    bundle,
                    "r_conflict_line",
                    kind=conflict.kind,
                    ref=escape_table_cell(conflict.ref),
                    field=conflict.field,
                    kept=escape_table_cell(truncate(str(conflict.kept), 80)),
                    dropped=escape_table_cell(truncate(str(conflict.dropped), 80)),
                )
                for conflict in report.conflicts
            ]
            lines.append("")
        if report.warnings:
            lines += [f"### {t(bundle, 'r_loader_warnings')}", ""]
            lines += [f"- {escape_table_cell(warning)}" for warning in report.warnings]
            lines.append("")

    lines += [f"## {t(bundle, 'issues')}", ""]
    if not bundle.issues:
        lines += [t(bundle, "no_issues"), ""]
    else:
        lines += ["| severity | code | message | ref |", "| --- | --- | --- | --- |"]
        for issue in bundle.issues:
            lines.append(
                f"| {issue.severity} | `{issue.code}` | {escape_table_cell(issue.message)} | `{escape_table_cell(issue.ref)}` |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
