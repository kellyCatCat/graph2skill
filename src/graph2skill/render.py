def decision_path_lines(bundle: SkillBundle, view: TreeNodeView, indent: int = 0) -> List[str]:
    lines: List[str] = []
    pad = "  " * indent
    label = view.node.label if view.node else view.node_id
    edge = relation_label(view.via.type, bundle.options.lang) if view.via else ""
    type_label = node_type_label(view.node.type, bundle.options.lang) if view.node else "?"
    head = f"{pad}- **[{type_label}]** [{one_line(label)}](#{anchor(view.node_id)})"
    if edge and view.depth > 0 and edge != type_label:
        head += f" _{edge}_"
    if view.repeated:
        head += f" {t(bundle, 'see_above')}"
    if view.truncated:
        head += f" {t(bundle, 'truncated')}"
    lines.append(head)
    condition = view.via.condition if view.via else ""
    if condition and view.node and one_line(condition) != one_line(view.node.label):
        lines.append(f"{pad}  - {one_line(condition)}")
    if view.node is not None:
        for command in view.node.commands[:3]:
            lines.append(f"{pad}  - `{one_line(command)}`")
    for child in view.children:
        lines += decision_path_lines(bundle, child, indent + 1)
    return lines


def _mermaid_label(text: str) -> str:
    cleaned = one_line(text).replace('"', "'").replace("[", "(").replace("]", ")")
    cleaned = cleaned.replace("{", "(").replace("}", ")").replace("|", "/")
    return truncate(cleaned, 42)


def mermaid_lines(bundle: SkillBundle, tree: ResolvedTree) -> List[str]:
    """A flowchart of the tree, skipped when it would be unreadable."""
    if not bundle.options.diagrams or len(tree.node_ids) > bundle.options.max_diagram_nodes:
        return []
    ids: Dict[str, str] = {}
    body: List[str] = []
    edges: List[str] = []

    def node_key(node_id: str) -> str:
        if node_id not in ids:
            ids[node_id] = f"N{len(ids)}"
        return ids[node_id]

    def walk(view: TreeNodeView) -> None:
        key = node_key(view.node_id)
        if len(body) == len(ids) - 1:
            label = view.node.label if view.node else view.node_id
            type_label = node_type_label(view.node.type, bundle.options.lang) if view.node else "?"
            body.append(f'    {key}["{_mermaid_label(type_label)}: {_mermaid_label(label)}"]')
        for child in view.children:
            child_key = node_key(child.node_id)
            if len(body) == len(ids) - 1:
                label = child.node.label if child.node else child.node_id
                type_label = node_type_label(child.node.type, bundle.options.lang) if child.node else "?"
                body.append(f'    {child_key}["{_mermaid_label(type_label)}: {_mermaid_label(label)}"]')
            child_type_label = node_type_label(child.node.type, bundle.options.lang) if child.node else ""
            edge_label = relation_label(child.via.type, bundle.options.lang) if child.via else ""
            if edge_label == child_type_label:
                edge_label = ""
            if edge_label:
                edges.append(f'    {key} -->|{_mermaid_label(edge_label)}| {child_key}')
            else:
                edges.append(f"    {key} --> {child_key}")
            if not child.repeated:
                walk(child)

    walk(tree.root)
    if not body:
        return []
    return ["```mermaid", "flowchart TD"] + body + edges + ["```", ""]


