def _sources_text(items: Sequence[str]) -> str:
    return ", ".join(f"`{item}`" for item in items) if items else "-"


def _provenance_lines(bundle: SkillBundle, items: Sequence[Provenance], indent: str = "") -> List[str]:
    lines: List[str] = []
    for prov in items:
        parts: List[str] = []
        if prov.source_path:
            parts.append(f"`{prov.source_path}`")
        if prov.locator:
            parts.append(one_line(prov.locator))
        if prov.anchor:
            parts.append(f"`{prov.anchor[:23]}…`" if len(prov.anchor) > 24 else f"`{prov.anchor}`")
        head = " · ".join(part for part in parts if part) or "-"
        lines.append(f"{indent}- {head}")
        if prov.excerpt:
            lines.append(f"{indent}  > {truncate(prov.excerpt, bundle.options.excerpt_limit)}")
    return lines


def node_headline(bundle: SkillBundle, node: Node) -> str:
    return f"[{node_type_label(node.type, bundle.options.lang)}] {one_line(node.label)}"


def node_detail_lines(
    bundle: SkillBundle,
    node: Node,
    level: int = 3,
    children: Optional[Sequence[TreeNodeView]] = None,
) -> List[str]:
    """Full markdown block describing one node."""
    hashes = "#" * max(2, min(level, 6))
    lines: List[str] = [f'<a id="{anchor(node.id)}"></a>', "", f"{hashes} {node_headline(bundle, node)}", ""]
    meta: List[str] = [f"`{node.id}`"]
    if node.execution_class:
        meta.append(f"executionClass: `{node.execution_class}`")
    if node.scenario_id and node.scenario_id != node.id:
        meta.append(f"scenarioId: `{node.scenario_id}`")
    if node.sources:
        meta.append(f"{t(bundle, 'sources')}: {_sources_text(node.sources)}")
    if node.source_version:
        meta.append(f"version: `{node.source_version}`")
    lines.append(" · ".join(meta))
    lines.append("")

    description = one_line(node.description)
    if description and description != one_line(node.name):
        lines += [f"**{t(bundle, 'description')}**: {description}", ""]

    observations = [obs for obs in node.observations if one_line(obs) != one_line(node.name)]
    if observations:
        lines.append(f"**{t(bundle, 'observations')}**")
        lines += [f"- {one_line(obs)}" for obs in observations]
        lines.append("")

    if node.commands:
        lines.append(f"**{t(bundle, 'commands')}**")
        lines.append("")
        lines += fence("\n".join(node.commands))
        lines.append("")

    extra = node.extra_data
    if extra:
        lines.append(f"**{t(bundle, 'extra')}**")
        for key, value in extra.items():
            if isinstance(value, (list, dict)):
                rendered = truncate(str(value), 300)
            else:
                rendered = one_line(str(value))
            lines.append(f"- `{key}`: {rendered}")
        lines.append("")

    if children:
        lines.append(f"**{t(bundle, 'children')}**")
        for child in children:
            label = child.node.label if child.node else child.node_id
            edge = relation_label(child.via.type, bundle.options.lang) if child.via else ""
            condition = child.via.condition if child.via else ""
            prefix = f"({edge}) " if edge else ""
            suffix = f" — {one_line(condition)}" if condition and condition != one_line(label) else ""
            lines.append(f"- {prefix}[{one_line(label)}](#{anchor(child.node_id)}){suffix}")
        lines.append("")

    provenance = node.provenance
    if provenance:
        lines.append(f"**{t(bundle, 'provenance')}**")
        lines += _provenance_lines(bundle, provenance)
        lines.append("")
    return lines


