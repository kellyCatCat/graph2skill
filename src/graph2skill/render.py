def t(bundle: SkillBundle, key: str, **fmt: object) -> str:
    table = LABELS.get(bundle.options.lang, LABELS[ZH])
    text = table.get(key, LABELS[ZH].get(key, key))
    return text.format(**fmt) if fmt else text


